import { createPrivateKey, createPublicKey, randomBytes } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import {
  base58Encode,
  buildSignedNearTransaction,
  NearRpcChainGateway,
  parseNearEd25519SecretKey,
} from "../src/shared/near-rpc-gateway";

const ED25519_PKCS8_PREFIX = Buffer.from("302e020100300506032b657004220420", "hex");

function loadDotEnvLocal(): Record<string, string> {
  const envPath = resolve(process.cwd(), ".env.local");
  if (!existsSync(envPath)) return {};
  const content = readFileSync(envPath, "utf8");
  const out: Record<string, string> = {};
  for (const line of content.split(/\r?\n/)) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith("#")) continue;
    const eqIdx = trimmed.indexOf("=");
    if (eqIdx === -1) continue;
    const key = trimmed.slice(0, eqIdx).trim();
    const val = trimmed.slice(eqIdx + 1).trim();
    out[key] = val;
  }
  return out;
}

function generateNearEd25519Keypair(): {
  secretKeyNear: string;
  publicKeyNear: string;
} {
  const seed32 = randomBytes(32);
  const pkcs8Der = Buffer.concat([ED25519_PKCS8_PREFIX, seed32]);
  const privKey = createPrivateKey({ key: pkcs8Der, format: "der", type: "pkcs8" });
  const pubSpki = createPublicKey(privKey).export({ format: "der", type: "spki" });
  const pub32 = new Uint8Array(pubSpki.subarray(pubSpki.length - 32));
  const full64 = new Uint8Array(64);
  full64.set(seed32, 0);
  full64.set(pub32, 32);
  return {
    secretKeyNear: `ed25519:${base58Encode(full64)}`,
    publicKeyNear: `ed25519:${base58Encode(pub32)}`,
  };
}

async function provisionTestnetAccount(
  accountId: string,
  publicKeyNear: string,
): Promise<void> {
  console.log(`Provisioning new NEAR Testnet account: ${accountId} ...`);
  const res = await fetch("https://helper.testnet.near.org/account", {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify({
      newAccountId: accountId,
      newAccountPublicKey: publicKeyNear,
    }),
  });
  if (!res.ok) {
    const errText = await res.text();
    throw new Error(
      `Failed to provision NEAR Testnet account via helper (${res.status}): ${errText}`,
    );
  }
}

/**
 * Deploy `contracts/ledgerly-escrow` WASM to NEAR Testnet and initialize `new(owner, token)`.
 * Automatically provisions a fresh Testnet account and writes `.env.local` if not yet configured.
 */
async function main() {
  const localEnv = loadDotEnvLocal();
  const rpcUrl =
    process.env.NEAR_RPC_URL ?? localEnv.NEAR_RPC_URL ?? "https://test.rpc.fastnear.com";
  let contractId =
    process.env.NEAR_ESCROW_CONTRACT_ID ?? localEnv.NEAR_ESCROW_CONTRACT_ID;
  let secretKey =
    process.env.NEAR_OPERATOR_PRIVATE_KEY ?? localEnv.NEAR_OPERATOR_PRIVATE_KEY;

  if (!contractId || !secretKey) {
    const suffix = randomBytes(4).toString("hex");
    contractId = `ledgerly-escrow-${suffix}.testnet`;
    const kp = generateNearEd25519Keypair();
    secretKey = kp.secretKeyNear;

    await provisionTestnetAccount(contractId, kp.publicKeyNear);

    const envFileContent = [
      `# Auto-generated by scripts/deploy-testnet.ts`,
      `NEAR_RPC_URL=${rpcUrl}`,
      `NEAR_ESCROW_CONTRACT_ID=${contractId}`,
      `NEAR_USDC_CONTRACT_ID=${contractId}`,
      `NEAR_OPERATOR_ACCOUNT_ID=${contractId}`,
      `NEAR_OPERATOR_PRIVATE_KEY=${secretKey}`,
      `LEDGERLY_INDEXER_TOKEN=ledgerly_testnet_indexer_secret`,
      "",
    ].join("\n");
    const envPath = resolve(process.cwd(), ".env.local");
    writeFileSync(envPath, envFileContent, "utf8");
    console.log(`✓ Saved NEAR Testnet credentials to ${envPath}`);
  }

  const usdcTokenId =
    process.env.NEAR_USDC_CONTRACT_ID ??
    localEnv.NEAR_USDC_CONTRACT_ID ??
    contractId;

  const wasmPath = resolve(
    process.cwd(),
    "contracts/ledgerly-escrow/target/wasm32-unknown-unknown/release/ledgerly_escrow.wasm",
  );
  const wasmBytes = new Uint8Array(readFileSync(wasmPath));
  console.log(`Loaded WASM binary (${wasmBytes.byteLength} bytes) from ${wasmPath}`);

  const parsedKey = parseNearEd25519SecretKey(secretKey);
  console.log(`Deploying to ${contractId} using key ${parsedKey.publicKeyNear}...`);

  const akRes = await fetch(rpcUrl, {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify({
      jsonrpc: "2.0",
      id: "deploy-ak",
      method: "query",
      params: {
        request_type: "view_access_key",
        finality: "optimistic",
        account_id: contractId,
        public_key: parsedKey.publicKeyNear,
      },
    }),
  });
  const akBody = (await akRes.json()) as {
    result?: { nonce: number; block_hash: string };
    error?: unknown;
  };
  if (!akBody.result) {
    throw new Error(
      `Failed to query access key on ${contractId}: ${JSON.stringify(akBody.error)}`,
    );
  }

  // Check if contract state already exists so re-deployment is idempotent
  const acctRes = await fetch(rpcUrl, {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify({
      jsonrpc: "2.0",
      id: "view-acct",
      method: "query",
      params: {
        request_type: "view_account",
        finality: "optimistic",
        account_id: contractId,
      },
    }),
  });
  const acctBody = (await acctRes.json()) as {
    result?: { code_hash?: string };
  };
  const alreadyDeployed =
    acctBody.result?.code_hash &&
    acctBody.result.code_hash !== "11111111111111111111111111111111";

  const actions: Parameters<typeof buildSignedNearTransaction>[0]["actions"] = [
    {
      kind: "DeployContract",
      wasmBytes,
    },
  ];
  if (!alreadyDeployed) {
    actions.push({
      kind: "FunctionCall",
      methodName: "new",
      argsJson: {
        owner: contractId,
        token: usdcTokenId,
      },
      gas: 50_000_000_000_000n,
      depositYocto: 0n,
    });
  } else {
    actions.push({
      kind: "FunctionCall",
      methodName: "set_token",
      argsJson: {
        token: usdcTokenId,
      },
      gas: 30_000_000_000_000n,
      depositYocto: 0n,
    });
  }

  const signed = buildSignedNearTransaction({
    signerId: contractId,
    signerSeed32: parsedKey.seed32,
    signerPublicKey32: parsedKey.publicKey32,
    nonce: BigInt(akBody.result.nonce) + 1n,
    receiverId: contractId,
    blockHashBase58: akBody.result.block_hash,
    actions,
  });

  const txRes = await fetch(rpcUrl, {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify({
      jsonrpc: "2.0",
      id: "deploy-tx",
      method: "send_tx",
      params: {
        signed_tx_base64: signed.signedTxBase64,
        wait_until: "EXECUTED_OPTIMISTIC",
      },
    }),
  });
  const txBody = (await txRes.json()) as {
    result?: {
      status?: { Failure?: unknown };
      transaction?: { hash: string };
    };
    error?: unknown;
  };
  if (txBody.error) {
    throw new Error(`Deploy transaction failed: ${JSON.stringify(txBody.error)}`);
  }
  if (txBody.result?.status && "Failure" in txBody.result.status) {
    throw new Error(
      `Deploy execution failed on-chain: ${JSON.stringify(txBody.result.status.Failure)}`,
    );
  }

  const txHash = txBody.result?.transaction?.hash ?? signed.txHashBase58;
  console.log(`✓ Deployed & initialized ledgerly-escrow on ${contractId}`);
  console.log(`✓ Deploy Transaction Hash: ${txHash}`);
  console.log(`✓ Explorer: https://testnet.nearblocks.io/txns/${txHash}`);

  // Smoke-test live RPC view + write lifecycle on NEAR Testnet
  const gw = new NearRpcChainGateway({
    rpcUrl,
    escrowContractId: contractId as never,
    usdcContractId: usdcTokenId as never,
    operatorAccountId: contractId as never,
    operatorPrivateKey: secretKey,
  });
  const smokeEscrowId = randomBytes(32).toString("hex") as never;
  const smokeCommitment = randomBytes(32).toString("hex");
  const refundAfterNs = BigInt(Date.now() + 48 * 3600 * 1000) * 1_000_000n;

  const regRes = await gw.registerEscrow({
    escrowId: smokeEscrowId,
    kind: "Payment",
    commitment: smokeCommitment,
    refundAfterNs,
  });
  console.log(`✓ Live register() txHash: ${regRes.txHash}`);

  const depTxHash = await gw.simulateDeposit({
    escrowId: smokeEscrowId,
    depositor: "kyoto-living.testnet" as never,
    amountMinor: 125_000_000n,
  });
  console.log(`✓ Live ft_transfer_call() deposit txHash: ${depTxHash}`);

  const heldView = await gw.getEscrow(smokeEscrowId);
  console.log(
    `✓ Live get_escrow() after deposit: status=${heldView?.status}, heldMinor=${heldView?.heldMinor.toString()}`,
  );

  const relRes = await gw.release({
    escrowId: smokeEscrowId,
    receiver: "atelier-sari.ledgerly.testnet" as never,
    amountMinor: 125_000_000n,
  });
  console.log(`✓ Live release() settlement txHash: ${relRes.txHash}`);

  const closedView = await gw.getEscrow(smokeEscrowId);
  console.log(
    `✓ Live get_escrow() after settlement: status=${closedView?.status}, heldMinor=${closedView?.heldMinor.toString()}`,
  );

  const anchorRes = await gw.anchorAuditRoot(smokeCommitment);
  console.log(`✓ Live anchor() audit root txHash: ${anchorRes.txHash}`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
